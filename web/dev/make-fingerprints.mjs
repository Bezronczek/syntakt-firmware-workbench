// Dev tool: regenerate web/js/fingerprints.js from the official firmware file.
// The output holds SHA-256 digests only, never firmware bytes.
//   node web/dev/make-fingerprints.mjs [path/to/Syntakt_OS1.41.syx]
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import * as fw from "../js/syntakt-fw.js";

const out = new URL("../js/fingerprints.js", import.meta.url);
if (!existsSync(out)) writeFileSync(out, "export const FINGERPRINTS = { registry: \"\", sections: {} };\n"); // bootstrap for the import below
const { computeFingerprints } = await import("../js/workbench.js");

const path = process.argv[2] || "work/Syntakt_OS1.41.syx";
const file = new Uint8Array(readFileSync(path));
const sha = await fw.sha256hex(file);
if (!(sha in fw.SUPPORTED)) throw new Error("not a supported official file: " + sha);
const fp = await computeFingerprints(fw.parseSyx(file));
writeFileSync(out,
  "// GENERATED by web/dev/make-fingerprints.mjs from the official " + fw.SUPPORTED[sha] + " file.\n" +
  "// SHA-256 digests only: no firmware bytes. Regenerate whenever mod regions change.\n" +
  "export const FINGERPRINTS = " + JSON.stringify(fp, null, 2) + ";\n");
console.log("wrote", out.pathname, "for", fw.SUPPORTED[sha]);
